// docs/73 D271 — the magic-link email in the language the app was using
// when it asked for the link (`language` on POST /api/auth/request-link),
// English when it's missing or unknown. Regional variants share their
// base language's text: nothing in this email differs between them.

export type EmailLanguage = 'en' | 'pt' | 'es' | 'fr';

interface MagicLinkCopy {
  subject: string;
  intro: string;
  orCode: string;
  homeScreen: string;
  expiry: string;
}

