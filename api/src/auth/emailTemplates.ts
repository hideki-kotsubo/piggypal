export function emailLanguage(tag: unknown): EmailLanguage {
  const base = typeof tag === 'string' ? tag.toLowerCase().split('-')[0] : '';
  return base === 'pt' || base === 'es' || base === 'fr' ? base : 'en';
}

// verifyUrl's token segment is base64url (A-Za-z0-9-_ only, generated by
// crypto.ts), the code is six digits, appBaseUrl is an env var, and the
// copy above is ours — safe to interpolate into the HTML with no escaping.
//
// docs/56 D204: the code is the only way to sign in an iOS home-screen
// app (a tapped link always opens Safari, whose storage is separate), so
// the email says so explicitly rather than leaving the code unexplained.
export function magicLinkEmail(
  verifyUrl: string,
  code: string,
  language: EmailLanguage,
): { subject: string; text: string; html: string } {
  const c = COPY[language];
  const spacedCode = `${code.slice(0, 3)} ${code.slice(3)}`;
  return {
    subject: c.subject,
    text: `${c.intro}\n\n${verifyUrl}\n\n${c.orCode} ${spacedCode}\n\n${c.homeScreen}\n\n${c.expiry}`,
    html:
      `<p>${c.intro}</p><p><a href="${verifyUrl}">${verifyUrl}</a></p><p>${c.orCode}</p>` +
      `<p style="font-size:28px;font-weight:600;letter-spacing:4px;font-family:ui-monospace,Menlo,Consolas,monospace">${spacedCode}</p>` +
      `<p>${c.homeScreen}</p><p>${c.expiry}</p>`,
  };
}
